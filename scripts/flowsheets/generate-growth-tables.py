"""Generate the WHO / CDC LMS reference tables the Growth flowsheet computes percentiles from.

Usage: python3 scripts/flowsheets/generate-growth-tables.py <source dir> [<out.ts>]

Rows are copied verbatim from the official files (CSV text as-is; xlsx numbers via repr) — no rounding,
no hand-typed numbers. Needs openpyxl. The source dir holds:
  WHO Child Growth Standards (who.int/tools/child-growth-standards/standards), the "0-to-5-years z-scores"
  monthly LMS workbooks (Month, L, M, S, ...):
    who_wfa_{boys,girls}.xlsx   weight-for-age        who_lhfa_{boys,girls}.xlsx  length/height-for-age
    who_wfl_{boys,girls}.xlsx   weight-for-length     who_hcfa_{boys,girls}.xlsx  head-circumference-for-age
  CDC 2000 growth charts (cdc.gov/growthcharts/percentile_data_files.htm), the z-score data files:
    cdc_wtage.csv  weight-for-age   cdc_statage.csv  stature-for-age   cdc_bmiagerev.csv  BMI-for-age
"""
import csv
import os
import sys

import openpyxl

SRC = sys.argv[1]
OUT = sys.argv[2] if len(sys.argv) > 2 else os.path.join(
    os.path.dirname(__file__), '..', '..', 'packages', 'zambdas', 'src', 'ehr', 'get-flowsheet', 'growth-tables.generated.ts'
)


def num(v):
    if isinstance(v, float) and v.is_integer() and abs(v) < 1e6:
        return str(int(v))
    return repr(v) if isinstance(v, float) else str(v)


def who(fname, xmax=None):
    wb = openpyxl.load_workbook(os.path.join(SRC, fname), read_only=True, data_only=True)
    rows = list(wb.active.iter_rows(values_only=True))
    head = [str(h) for h in rows[0]]
    ix = [head.index(c) for c in (head[0], 'L', 'M', 'S')]
    out = []
    for r in rows[1:]:
        if r[0] is None:
            continue
        if xmax is not None and r[0] > xmax:
            continue
        out.append([num(r[i]) for i in ix])
    return out


def cdc(fname, xmin=24, xmax=240):
    out = {'1': [], '2': []}
    with open(os.path.join(SRC, fname), newline='') as f:
        for r in csv.reader(f):
            if not r or r[0] == 'Sex':  # header (bmiagerev repeats it partway through)
                continue
            age = float(r[1])
            if xmin <= age <= xmax:
                out[r[0]].append([r[1], r[2], r[3], r[4]])  # verbatim text: Agemos, L, M, S
    return out


tables = {}
for ind, base, xmax in (('wfa', 'who_wfa', 24), ('lfa', 'who_lhfa', 24), ('wfl', 'who_wfl', None), ('hcfa', 'who_hcfa', 24)):
    for sex, word in (('male', 'boys'), ('female', 'girls')):
        tables[f'WHO {ind} {sex}'] = who(f'{base}_{word}.xlsx', xmax)
for ind, fname in (('wfa', 'cdc_wtage.csv'), ('sfa', 'cdc_statage.csv'), ('bmi', 'cdc_bmiagerev.csv')):
    t = cdc(fname)
    tables[f'CDC {ind} male'] = t['1']
    tables[f'CDC {ind} female'] = t['2']

lines = [
    '// GENERATED by scripts/flowsheets/generate-growth-tables.py from the official LMS files; do not hand-edit.',
    '// Each row is [x, L, M, S]. WHO Child Growth Standards (who.int), 0-24 months: wfa = weight-for-age,',
    '// lfa = length-for-age, hcfa = head-circumference-for-age (x = age in months), wfl = weight-for-length',
    '// (x = length in cm, 45-110). CDC 2000 growth charts (cdc.gov/growthcharts/data/zscore), 24-240 months:',
    '// wfa, sfa = stature-for-age, bmi = BMI-for-age (x = Agemos; 24, 24.5, 25.5, ... 239.5, 240).',
    '',
    "import { LmsRow } from 'utils/lib/helpers/vitals/growth-lms';",
    '',
    '// prettier-ignore',
    'export const GROWTH_TABLES: Record<string, LmsRow[]> = {',
]
for key, rows in tables.items():
    lines.append(f"  '{key}': [")
    for i in range(0, len(rows), 6):
        lines.append('    ' + ','.join('[' + ','.join(r) + ']' for r in rows[i:i + 6]) + ',')
    lines.append('  ],')
lines += ['};', '']
with open(OUT, 'w') as f:
    f.write('\n'.join(lines))
for k, rows in tables.items():
    print(f'{k:18s} rows={len(rows):4d}  x {rows[0][0]}..{rows[-1][0]}')
print('wrote', os.path.relpath(OUT), os.path.getsize(OUT), 'bytes')
