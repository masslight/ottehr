import { createHash } from 'crypto';
import * as fs from 'fs';
import * as path from 'path';
import * as prettier from 'prettier';
import { parseCdcCvx, parseCdcMvx } from 'utils/lib/types/data/immunization/vaccine-codes';

const SOURCE_DIR = path.resolve(__dirname, 'data/cdc-vaccines');
const TARGET_DIR = path.resolve(__dirname, '../packages/utils/lib/types/data/immunization');
const MANIFEST = path.join(SOURCE_DIR, 'sources.json');
const CDC_DOWNLOADS = 'https://www2a.cdc.gov/vaccines/iis/iisstandards/downloads';

type Manifest = Record<string, { url: string; retrievedAt: string; bytes: number; sha256: string }>;

const SOURCES = [
  { file: 'cvx.txt', parse: parseCdcCvx },
  { file: 'mvx.txt', parse: parseCdcMvx },
];

const TABLES = [
  {
    target: 'cvx-vaccines.generated.ts',
    title: 'Vaccines that can be ordered: active US CVX codes, in name order.',
    exportName: 'CVX_VACCINES',
    type: 'CvxVaccine',
    rows: (): unknown[] => parseCdcCvx(readSource('cvx.txt')),
  },
  {
    target: 'mvx-manufacturers.generated.ts',
    title: 'Active vaccine manufacturers (MVX codes), in code order.',
    exportName: 'MVX_MANUFACTURERS',
    type: 'MvxManufacturer',
    rows: (): unknown[] => parseCdcMvx(readSource('mvx.txt')),
  },
];

function readSource(file: string): string {
  return fs.readFileSync(path.join(SOURCE_DIR, file), 'utf-8');
}

async function download(): Promise<void> {
  const downloads = [];
  for (const { file, parse } of SOURCES) {
    const url = `${CDC_DOWNLOADS}/${file}`;
    const response = await fetch(url);
    if (!response.ok) throw new Error(`${url} answered HTTP ${response.status}`);
    const body = Buffer.from(await response.arrayBuffer());
    const rows = parse(new TextDecoder('utf-8', { fatal: true }).decode(body));
    downloads.push({ file, url, body, rows: rows.length });
  }

  const manifest: Manifest = fs.existsSync(MANIFEST) ? JSON.parse(fs.readFileSync(MANIFEST, 'utf-8')) : {};
  for (const { file, url, body, rows } of downloads) {
    const sha256 = createHash('sha256').update(body).digest('hex');
    fs.writeFileSync(path.join(SOURCE_DIR, file), body);
    if (manifest[file]?.sha256 === sha256) {
      console.log(`${file}: unchanged since ${manifest[file].retrievedAt}`);
      continue;
    }
    manifest[file] = { url, retrievedAt: new Date().toISOString().slice(0, 10), bytes: body.length, sha256 };
    console.log(`${file}: downloaded ${body.length} bytes, ${rows} rows kept`);
  }
  fs.writeFileSync(MANIFEST, `${JSON.stringify(manifest, null, 2)}\n`);
}

async function generate(): Promise<void> {
  for (const table of TABLES) {
    const rows = table.rows();
    const source = [
      `// ${table.title}`,
      '// Generated by `npm run codes:vaccines` from scripts/data/cdc-vaccines/ — do not edit by hand.',
      `import type { ${table.type} } from './vaccine-codes';`,
      '',
      `export const ${table.exportName}: readonly ${table.type}[] = [`,
      ...rows.map((row) => `  ${JSON.stringify(row)},`),
      '];',
      '',
    ].join('\n');
    const target = path.join(TARGET_DIR, table.target);
    const config = await prettier.resolveConfig(target);
    fs.writeFileSync(target, await prettier.format(source, { ...config, parser: 'typescript' }));
    console.log(`Wrote ${rows.length} rows to ${target}`);
  }
}

async function main(): Promise<void> {
  if (process.argv.includes('--download')) await download();
  await generate();
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
