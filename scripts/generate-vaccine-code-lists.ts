import * as fs from 'fs';
import * as path from 'path';
import * as prettier from 'prettier';
import { parseCdcNdcLookup, parseCvxPsv, parseMvxPsv } from 'utils/lib/types/data/immunization/vaccine-codes';

// Renders the vaccine catalog's code tables from the CDC downloads in scripts/data/cdc-vaccines/: the CVX
// vaccines a practice can switch on, the active MVX manufacturers, and the NDC crosswalk rows for those
// vaccines. Run via `npm run codes:vaccines` after refreshing a download; a unit test in utils
// (vaccine-codes.test.ts) fails when a committed table no longer matches its source.

const SOURCE_DIR = path.resolve(__dirname, 'data/cdc-vaccines');
const TARGET_DIR = path.resolve(__dirname, '../packages/utils/lib/types/data/immunization');

/** Packages whose sale ended before this date are left out of the NDC table. */
export const NDC_KEEP_ENDED_SINCE = '2024-01-01';

const read = (file: string): string => fs.readFileSync(path.join(SOURCE_DIR, file), 'utf-8');

async function write(
  target: string,
  header: string[],
  exportName: string,
  type: string,
  rows: unknown[]
): Promise<void> {
  const source = [
    ...header.map((line) => `// ${line}`),
    `import type { ${type} } from './vaccine-codes';`,
    '',
    `export const ${exportName}: readonly ${type}[] = [`,
    ...rows.map((row) => `  ${JSON.stringify(row)},`),
    '];',
    '',
  ].join('\n');
  const file = path.join(TARGET_DIR, target);
  const config = await prettier.resolveConfig(file);
  fs.writeFileSync(file, await prettier.format(source, { ...config, filepath: file }));
  console.log(`Wrote ${rows.length} rows to ${path.relative(process.cwd(), file)}`);
}

async function main(): Promise<void> {
  const generated = 'Generated by `npm run codes:vaccines` from scripts/data/cdc-vaccines/ — do not edit by hand.';
  const cvx = parseCvxPsv(read('cvx-active.psv'));
  await write(
    'cvx-vaccines.generated.ts',
    ['The vaccines a practice can switch on in the In-House Medications catalog: current US CVX codes.', generated],
    'CVX_VACCINES',
    'CvxVaccine',
    cvx
  );
  await write(
    'mvx-manufacturers.generated.ts',
    ['Active vaccine manufacturers (CDC MVX codes).', generated],
    'MVX_MANUFACTURERS',
    'MvxManufacturer',
    parseMvxPsv(read('mvx-active.psv'))
  );
  await write(
    'ndc-vaccines.generated.ts',
    ['CDC NDC crosswalk rows for the offered vaccines: which box is which vaccine from which manufacturer.', generated],
    'NDC_VACCINE_PRODUCTS',
    'NdcVaccineProduct',
    parseCdcNdcLookup(read('cdc-ndc-lookup.txt'), new Set(cvx.map((vaccine) => vaccine.cvx)), NDC_KEEP_ENDED_SINCE)
  );
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
